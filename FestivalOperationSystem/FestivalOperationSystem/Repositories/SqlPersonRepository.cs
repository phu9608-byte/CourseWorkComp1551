using FestivalOperationSystem.Models;
using Microsoft.Data.SqlClient;

namespace FestivalOperationSystem.Repositories
{
    /// <summary>
    /// SQL Server implementation of <see cref="IPersonRepository"/>.
    /// This is the only class in the application that contains SQL.
    /// Every value is passed as a parameter (never joined into the SQL text) to prevent SQL injection.
    /// </summary>
    public class SqlPersonRepository : IPersonRepository
    {
        // Columns read for every person. The role-specific columns are NULL for the other roles.
        // {0} is the source of the People rows (the ActivePeople view or the People table)
        // and {1} is where DeletedAt comes from (the view has no such column, so active reads use NULL).
        private const string SelectPeopleSql = @"
            SELECT p.PersonID, p.[Name], p.Telephone, p.Email, p.[Role], {1} AS DeletedAt,
                   pf.Fee, c.HourlyRate, c.EmploymentType, c.WeeklyHours, v.StallName
            FROM {0} p
            LEFT JOIN Performers pf ON pf.PersonID = p.PersonID
            LEFT JOIN Crew c ON c.PersonID = p.PersonID
            LEFT JOIN Vendors v ON v.PersonID = p.PersonID";

        // Active reads go through the ActivePeople view so they can never include deleted people.
        private static readonly string SelectActiveSql =
            string.Format(SelectPeopleSql, "ActivePeople", "CAST(NULL AS datetime2)");

        // The People table is read directly only when deleted people are wanted.
        private static readonly string SelectAnySql =
            string.Format(SelectPeopleSql, "People", "p.DeletedAt");

        private readonly string _connectionString;

        /// <summary>Creates a repository that connects with the given connection string.</summary>
        public SqlPersonRepository(string connectionString)
        {
            _connectionString = connectionString;
        }

        /// <inheritdoc />
        public List<Person> GetAll()
        {
            return Run(connection => LoadPeople(connection, null,
                SelectActiveSql + " ORDER BY p.PersonID"));
        }

        /// <inheritdoc />
        public List<Person> GetByRole(PersonRole role)
        {
            return Run(connection => LoadPeople(connection, null,
                SelectActiveSql + " WHERE p.[Role] = @Role ORDER BY p.PersonID",
                new SqlParameter("@Role", role.ToString())));
        }

        /// <inheritdoc />
        public Person? GetById(int personId)
        {
            return Run(connection => LoadPeople(connection, null,
                SelectActiveSql + " WHERE p.PersonID = @PersonID",
                new SqlParameter("@PersonID", personId)).FirstOrDefault());
        }

        /// <inheritdoc />
        public List<Person> GetDeleted()
        {
            return Run(connection => LoadPeople(connection, null,
                SelectAnySql + " WHERE p.IsDeleted = 1 ORDER BY p.DeletedAt DESC"));
        }

        /// <inheritdoc />
        public Person? FindByEmail(string email)
        {
            // The database collation is case-insensitive, so "A@x.com" matches "a@x.com".
            return Run(connection => LoadPeople(connection, null,
                SelectAnySql + " WHERE p.Email = @Email",
                new SqlParameter("@Email", email.Trim())).FirstOrDefault());
        }

        /// <inheritdoc />
        public int Add(Person person)
        {
            return RunInTransaction((connection, transaction) =>
            {
                // 1. Shared fields. OUTPUT returns the ID generated by IDENTITY.
                int newId = (int)CreateCommand(connection, transaction,
                    @"INSERT INTO People ([Name], Telephone, Email, [Role])
                      OUTPUT INSERTED.PersonID
                      VALUES (@Name, @Telephone, @Email, @Role)",
                    new SqlParameter("@Name", person.Name),
                    new SqlParameter("@Telephone", person.Telephone),
                    new SqlParameter("@Email", person.Email),
                    new SqlParameter("@Role", person.Role.ToString())).ExecuteScalar()!;
                person.PersonId = newId;

                // 2. Role-specific row and its link table rows.
                InsertRoleData(connection, transaction, person);
                return newId;
            });
        }

        /// <inheritdoc />
        public void Update(Person person)
        {
            RunInTransaction((connection, transaction) =>
            {
                CreateCommand(connection, transaction,
                    @"UPDATE People SET [Name] = @Name, Telephone = @Telephone, Email = @Email
                      WHERE PersonID = @PersonID AND IsDeleted = 0",
                    new SqlParameter("@Name", person.Name),
                    new SqlParameter("@Telephone", person.Telephone),
                    new SqlParameter("@Email", person.Email),
                    new SqlParameter("@PersonID", person.PersonId)).ExecuteNonQuery();

                // Simplest correct way to save role data: remove the old rows, then insert the new ones.
                // The role itself cannot change, so only this person's own role table is touched.
                DeleteRoleData(connection, transaction, person);
                InsertRoleData(connection, transaction, person);
                return 0;
            });
        }

        /// <inheritdoc />
        public void SoftDelete(int personId)
        {
            // Only flags the row: no DELETE statement runs, so the record can be restored later.
            Run(connection => CreateCommand(connection, null,
                @"UPDATE People SET IsDeleted = 1, DeletedAt = SYSDATETIME()
                  WHERE PersonID = @PersonID AND IsDeleted = 0",
                new SqlParameter("@PersonID", personId)).ExecuteNonQuery());
        }

        /// <inheritdoc />
        public void Restore(int personId)
        {
            Run(connection => CreateCommand(connection, null,
                @"UPDATE People SET IsDeleted = 0, DeletedAt = NULL
                  WHERE PersonID = @PersonID AND IsDeleted = 1",
                new SqlParameter("@PersonID", personId)).ExecuteNonQuery());
        }

        /// <summary>
        /// Runs the given SELECT and turns each row into the right Person subclass,
        /// then attaches genres and categories.
        /// </summary>
        private static List<Person> LoadPeople(SqlConnection connection, SqlTransaction? transaction,
            string sql, params SqlParameter[] parameters)
        {
            List<Person> people = new List<Person>();
            using (SqlDataReader reader = CreateCommand(connection, transaction, sql, parameters).ExecuteReader())
            {
                while (reader.Read())
                {
                    people.Add(ReadPerson(reader));
                }
            }

            // Genres and categories are loaded separately and matched by PersonID.
            Dictionary<int, List<string>> genres = LoadNames(connection, transaction,
                @"SELECT pg.PersonID, g.GenreName FROM PerformerGenres pg
                  JOIN Genres g ON g.GenreID = pg.GenreID ORDER BY g.GenreName");
            Dictionary<int, List<string>> categories = LoadNames(connection, transaction,
                @"SELECT vc.PersonID, c.CategoryName FROM VendorCategories vc
                  JOIN Categories c ON c.CategoryID = vc.CategoryID ORDER BY c.CategoryName");

            foreach (Person person in people)
            {
                if (person is Performer performer && genres.TryGetValue(person.PersonId, out List<string>? genreNames))
                {
                    performer.SetGenres(genreNames);
                }
                else if (person is Vendor vendor && categories.TryGetValue(person.PersonId, out List<string>? categoryNames))
                {
                    vendor.SetCategories(categoryNames);
                }
            }
            return people;
        }

        /// <summary>
        /// Builds one Person from the current row. Mapping a row to an object has to know the concrete
        /// type, so the role decides which subclass to create here.
        /// </summary>
        private static Person ReadPerson(SqlDataReader reader)
        {
            string name = reader.GetString(reader.GetOrdinal("Name"));
            string telephone = reader.GetString(reader.GetOrdinal("Telephone"));
            string email = reader.GetString(reader.GetOrdinal("Email"));
            PersonRole role = Enum.Parse<PersonRole>(reader.GetString(reader.GetOrdinal("Role")));

            // Genres and categories start empty and are attached afterwards by LoadPeople.
            Person person = role switch
            {
                PersonRole.Performer => new Performer(name, telephone, email,
                    reader.GetDecimal(reader.GetOrdinal("Fee")), new List<string>()),
                PersonRole.Crew => new Crew(name, telephone, email,
                    reader.GetDecimal(reader.GetOrdinal("HourlyRate")),
                    Enum.Parse<EmploymentType>(reader.GetString(reader.GetOrdinal("EmploymentType"))),
                    reader.GetInt32(reader.GetOrdinal("WeeklyHours"))),
                _ => new Vendor(name, telephone, email,
                    reader.GetString(reader.GetOrdinal("StallName")), new List<string>())
            };

            person.PersonId = reader.GetInt32(reader.GetOrdinal("PersonID"));
            int deletedAtColumn = reader.GetOrdinal("DeletedAt");
            person.SetDeletionState(reader.IsDBNull(deletedAtColumn) ? null : reader.GetDateTime(deletedAtColumn));
            return person;
        }

        /// <summary>Reads (PersonID, name) pairs into a lookup of names per person.</summary>
        private static Dictionary<int, List<string>> LoadNames(SqlConnection connection, SqlTransaction? transaction, string sql)
        {
            Dictionary<int, List<string>> namesByPerson = new Dictionary<int, List<string>>();
            using (SqlDataReader reader = CreateCommand(connection, transaction, sql).ExecuteReader())
            {
                while (reader.Read())
                {
                    int personId = reader.GetInt32(0);
                    if (!namesByPerson.ContainsKey(personId))
                    {
                        namesByPerson[personId] = new List<string>();
                    }
                    namesByPerson[personId].Add(reader.GetString(1));
                }
            }
            return namesByPerson;
        }

        /// <summary>Inserts the role table row, plus genre or category links, for a person who already has an ID.</summary>
        private static void InsertRoleData(SqlConnection connection, SqlTransaction transaction, Person person)
        {
            SqlParameter id = new SqlParameter("@PersonID", person.PersonId);
            switch (person)
            {
                case Performer performer:
                    CreateCommand(connection, transaction,
                        "INSERT INTO Performers (PersonID, Fee) VALUES (@PersonID, @Fee)",
                        id, new SqlParameter("@Fee", performer.Fee)).ExecuteNonQuery();
                    foreach (string genre in performer.Genres)
                    {
                        int genreId = GetOrCreateId(connection, transaction, "Genres", "GenreID", "GenreName", genre);
                        CreateCommand(connection, transaction,
                            "INSERT INTO PerformerGenres (PersonID, GenreID) VALUES (@PersonID, @GenreID)",
                            new SqlParameter("@PersonID", person.PersonId),
                            new SqlParameter("@GenreID", genreId)).ExecuteNonQuery();
                    }
                    break;

                case Crew crew:
                    CreateCommand(connection, transaction,
                        @"INSERT INTO Crew (PersonID, HourlyRate, EmploymentType, WeeklyHours)
                          VALUES (@PersonID, @HourlyRate, @EmploymentType, @WeeklyHours)",
                        id,
                        new SqlParameter("@HourlyRate", crew.HourlyRate),
                        new SqlParameter("@EmploymentType", crew.EmploymentType.ToString()),
                        new SqlParameter("@WeeklyHours", crew.WeeklyHours)).ExecuteNonQuery();
                    break;

                case Vendor vendor:
                    CreateCommand(connection, transaction,
                        "INSERT INTO Vendors (PersonID, StallName) VALUES (@PersonID, @StallName)",
                        id, new SqlParameter("@StallName", vendor.StallName)).ExecuteNonQuery();
                    foreach (string category in vendor.Categories)
                    {
                        int categoryId = GetOrCreateId(connection, transaction, "Categories", "CategoryID", "CategoryName", category);
                        CreateCommand(connection, transaction,
                            "INSERT INTO VendorCategories (PersonID, CategoryID) VALUES (@PersonID, @CategoryID)",
                            new SqlParameter("@PersonID", person.PersonId),
                            new SqlParameter("@CategoryID", categoryId)).ExecuteNonQuery();
                    }
                    break;
            }
        }

        /// <summary>Removes the role table row and its link rows, so <see cref="InsertRoleData"/> can write fresh ones.</summary>
        private static void DeleteRoleData(SqlConnection connection, SqlTransaction transaction, Person person)
        {
            // Link rows first, because they reference the role table row.
            string[] statements = person.Role switch
            {
                PersonRole.Performer => new[]
                {
                    "DELETE FROM PerformerGenres WHERE PersonID = @PersonID",
                    "DELETE FROM Performers WHERE PersonID = @PersonID"
                },
                PersonRole.Crew => new[] { "DELETE FROM Crew WHERE PersonID = @PersonID" },
                _ => new[]
                {
                    "DELETE FROM VendorCategories WHERE PersonID = @PersonID",
                    "DELETE FROM Vendors WHERE PersonID = @PersonID"
                }
            };
            foreach (string sql in statements)
            {
                CreateCommand(connection, transaction, sql, new SqlParameter("@PersonID", person.PersonId)).ExecuteNonQuery();
            }
        }

        /// <summary>
        /// Returns the ID of a genre or category by name, creating it first if it does not exist yet.
        /// Table and column names come from this class only, never from user input.
        /// </summary>
        private static int GetOrCreateId(SqlConnection connection, SqlTransaction transaction,
            string table, string idColumn, string nameColumn, string name)
        {
            object? existingId = CreateCommand(connection, transaction,
                $"SELECT {idColumn} FROM {table} WHERE {nameColumn} = @Name",
                new SqlParameter("@Name", name)).ExecuteScalar();
            if (existingId != null)
            {
                return (int)existingId;
            }
            return (int)CreateCommand(connection, transaction,
                $"INSERT INTO {table} ({nameColumn}) OUTPUT INSERTED.{idColumn} VALUES (@Name)",
                new SqlParameter("@Name", name)).ExecuteScalar()!;
        }

        /// <summary>Creates a command with its parameters, attached to the transaction if there is one.</summary>
        private static SqlCommand CreateCommand(SqlConnection connection, SqlTransaction? transaction,
            string sql, params SqlParameter[] parameters)
        {
            SqlCommand command = new SqlCommand(sql, connection, transaction);
            command.Parameters.AddRange(parameters);
            return command;
        }

        /// <summary>Opens a connection, runs the work and turns SQL errors into <see cref="DataAccessException"/>.</summary>
        private T Run<T>(Func<SqlConnection, T> work)
        {
            try
            {
                using SqlConnection connection = new SqlConnection(_connectionString);
                connection.Open();
                return work(connection);
            }
            catch (SqlException ex)
            {
                throw new DataAccessException("The database could not be reached or rejected the change. " + ex.Message, ex);
            }
        }

        /// <summary>
        /// Like <see cref="Run{T}"/>, but inside a transaction: either every statement is saved or none is.
        /// Used when one change writes to several tables.
        /// </summary>
        private T RunInTransaction<T>(Func<SqlConnection, SqlTransaction, T> work)
        {
            return Run(connection =>
            {
                using SqlTransaction transaction = connection.BeginTransaction();
                try
                {
                    T result = work(connection, transaction);
                    transaction.Commit();
                    return result;
                }
                catch
                {
                    transaction.Rollback();
                    throw;
                }
            });
        }
    }
}
